def field(collection, name, type_, interface, title, options=None):
    components = {'input': 'Input', 'integer': 'InputNumber', 'datetime': 'DatePicker', 'm2o': 'AssociationField', 'select': 'Select'}
    opts = {'uiSchema': {'title': title, 'x-component': components.get(interface, 'Input')}}
    if options: opts.update(options)
    insert('fields', {'key': 's3_' + collection + '_' + name, 'name': name, 'type': type_, 'interface': interface,
        'collectionName': collection, 'options': opts, 'sort': 20 + len(sql)})

