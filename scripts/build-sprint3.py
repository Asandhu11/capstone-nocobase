def q(value):
    if value is None: return 'NULL'
    if isinstance(value, bool): return 'true' if value else 'false'
    if isinstance(value, (int, float)): return str(value)
    if isinstance(value, (dict, list)): value = json.dumps(value, separators=(',', ':'))
    return "'" + str(value).replace("'", "''") + "'"
def insert(table, row, conflict='DO NOTHING'):
    columns = ','.join('"'+x+'"' for x in row)
    emit(f'INSERT INTO "{table}" ({columns}) VALUES ({",".join(q(x) for x in row.values())}) ON CONFLICT {conflict};')

